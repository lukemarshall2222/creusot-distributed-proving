//! The Lock_File `deps/lock.toml` (design: Data Models, R7.7).
//!
//! The file is TOML in one fixed layout: the header line, then per tool a
//! `[[tool]]` table with its fields in their order and a
//! `[[tool.platform]]` table per platform, each after one empty line.
//! `print` writes that layout and `parse` takes a text only if it is the
//! print of what it reads (R7.10 criterion 8): the hash of the file is in
//! every Verdict, so one set of pins has one text. A Lock_File that is
//! refused pins nothing (R7.7 criterion 3).

use serde::Deserialize;

use crate::{
    canonical_check::{self, LOCK_FILE},
    hash::Hash,
};

/// The first line of every Lock_File.
pub const HEADER: &str = "# Lock_File (R7.7). Generated by deps/gen-lock.sh; do not edit.\n";

#[derive(Clone, Debug, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct LockFile {
    #[serde(default)]
    pub tool: Vec<Tool>,
}

#[derive(Clone, Copy, Debug, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "kebab-case")]
pub enum Kind {
    UnpatchedSolver,
    SharingSolver,
    Checker,
    CheckerSignature,
    AletheRuleList,
    Why3,
    Why3find,
    Creusot,
    Lean,
    Tla,
    Kani,
    CargoMutants,
    Toolchain,
    Library,
}

impl Kind {
    /// The name of the kind in a Lock_File.
    pub fn name(self) -> &'static str {
        match self {
            Kind::UnpatchedSolver => "unpatched-solver",
            Kind::SharingSolver => "sharing-solver",
            Kind::Checker => "checker",
            Kind::CheckerSignature => "checker-signature",
            Kind::AletheRuleList => "alethe-rule-list",
            Kind::Why3 => "why3",
            Kind::Why3find => "why3find",
            Kind::Creusot => "creusot",
            Kind::Lean => "lean",
            Kind::Tla => "tla",
            Kind::Kani => "kani",
            Kind::CargoMutants => "cargo-mutants",
            Kind::Toolchain => "toolchain",
            Kind::Library => "library",
        }
    }
}

#[derive(Clone, Debug, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct Tool {
    pub name: String,
    pub version: String,
    pub kind: Kind,
    /// The prover name, for solvers.
    pub prover: Option<String>,
    /// Paths under `patches/` that the build applies.
    #[serde(default)]
    pub patches: Vec<String>,
    #[serde(default)]
    pub platform: Vec<Platform>,
}

#[derive(Clone, Debug, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct Platform {
    pub platform: String,
    /// `sha256:<64 hex digits>`.
    pub hash: String,
    pub upstream: Option<Upstream>,
}

#[derive(Clone, Debug, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct Upstream {
    pub published_checksum: Option<String>,
    pub tag: Option<String>,
    #[serde(default)]
    pub rebuild_hashes: Vec<String>,
}

#[derive(Debug)]
pub struct LockError(pub String);

impl std::fmt::Display for LockError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "Lock_File: {}", self.0)
    }
}

impl std::error::Error for LockError {}

fn parse_hash(text: &str) -> Option<Hash> {
    let hex = text.strip_prefix("sha256:")?;
    if hex.len() != 64 || !hex.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f')) {
        return None;
    }
    let mut out = [0u8; 32];
    for (i, byte) in out.iter_mut().enumerate() {
        *byte = u8::from_str_radix(&hex[2 * i..2 * i + 2], 16).ok()?;
    }
    Some(Hash(out))
}

impl LockFile {
    /// Parses a Lock_File. Every entry needs a version and well-formed
    /// content hashes (R7.7 criterion 6); a patched build may not be an
    /// Unpatched_Solver (R7.7 criterion 8).
    pub fn parse(text: &str) -> Result<LockFile, LockError> {
        let lock = LockFile::parse_lenient(text)?;
        canonical_check::check(LOCK_FILE, text.as_bytes(), lock.print().as_bytes())
            .map_err(|e| LockError(e.to_string()))?;
        Ok(lock)
    }

    /// The canonical text of the Lock_File.
    pub fn print(&self) -> String {
        let quote = |s: &str| format!("\"{s}\"");
        let list = |items: &[String]| format!("[{}]", items.iter().map(|i| quote(i)).collect::<Vec<_>>().join(", "));
        let mut out = String::from(HEADER);
        for tool in &self.tool {
            out.push_str("\n[[tool]]\n");
            out.push_str(&format!("name = {}\nversion = {}\n", quote(&tool.name), quote(&tool.version)));
            out.push_str(&format!("kind = {}\n", quote(tool.kind.name())));
            if let Some(prover) = &tool.prover {
                out.push_str(&format!("prover = {}\n", quote(prover)));
            }
            if !tool.patches.is_empty() {
                out.push_str(&format!("patches = {}\n", list(&tool.patches)));
            }
            for platform in &tool.platform {
                out.push_str("\n[[tool.platform]]\n");
                out.push_str(&format!("platform = {}\nhash = {}\n", quote(&platform.platform), quote(&platform.hash)));
                if let Some(upstream) = &platform.upstream {
                    let mut fields = Vec::new();
                    if let Some(checksum) = &upstream.published_checksum {
                        fields.push(format!("published_checksum = {}", quote(checksum)));
                    }
                    if let Some(tag) = &upstream.tag {
                        fields.push(format!("tag = {}", quote(tag)));
                    }
                    fields.push(format!("rebuild_hashes = {}", list(&upstream.rebuild_hashes)));
                    out.push_str(&format!("upstream = {{ {} }}\n", fields.join(", ")));
                }
            }
        }
        out
    }

    /// Reads a Lock_File in any layout, with every check of `parse` but the
    /// canonical-input check. For the tests of the tools that judge the
    /// contents of a Lock_File; nothing that pins a tool reads one this
    /// way.
    pub fn parse_lenient(text: &str) -> Result<LockFile, LockError> {
        let lock: LockFile = toml::from_str(text).map_err(|e| LockError(e.to_string()))?;
        // The printer writes strings as they are: one that would need an
        // escape has no canonical text.
        let plain = |s: &str| !s.chars().any(|c| c == '"' || c == '\\' || c.is_control());
        for tool in &lock.tool {
            let mut strings: Vec<&str> = vec![&tool.name, &tool.version];
            strings.extend(tool.prover.as_deref());
            strings.extend(tool.patches.iter().map(String::as_str));
            for platform in &tool.platform {
                strings.extend([platform.platform.as_str(), platform.hash.as_str()]);
                if let Some(upstream) = &platform.upstream {
                    strings.extend(upstream.published_checksum.as_deref());
                    strings.extend(upstream.tag.as_deref());
                    strings.extend(upstream.rebuild_hashes.iter().map(String::as_str));
                }
            }
            if let Some(bad) = strings.iter().find(|s| !plain(s)) {
                return Err(LockError(format!("{}: {bad:?} has a character that a Lock_File string may not have", tool.name)));
            }
        }
        for tool in &lock.tool {
            if tool.version.is_empty() {
                return Err(LockError(format!("{}: missing version", tool.name)));
            }
            if tool.kind == Kind::UnpatchedSolver && !tool.patches.is_empty() {
                return Err(LockError(format!("{}: a patched build marked unpatched-solver", tool.name)));
            }
            if matches!(tool.kind, Kind::UnpatchedSolver | Kind::SharingSolver) && tool.prover.is_none() {
                return Err(LockError(format!("{}: solver without a prover name", tool.name)));
            }
            for platform in &tool.platform {
                if parse_hash(&platform.hash).is_none() {
                    return Err(LockError(format!(
                        "{} ({}): malformed hash {:?}",
                        tool.name, platform.platform, platform.hash
                    )));
                }
            }
        }
        Ok(lock)
    }

    /// The hashes that the Lock_File pins on `platform` for tools of `kind`,
    /// with the tool.
    pub fn pins<'a>(
        &'a self,
        kind: Kind,
        platform: &'a str,
    ) -> impl Iterator<Item = (&'a Tool, Hash)> + 'a {
        self.tool.iter().filter(move |t| t.kind == kind).flat_map(move |t| {
            t.platform
                .iter()
                .filter(move |p| p.platform == platform)
                .map(move |p| (t, parse_hash(&p.hash).expect("checked by parse")))
        })
    }
}

/// The platform name of this build, as the Lock_File spells it.
pub fn current_platform() -> String {
    let os = match std::env::consts::OS {
        "macos" => "darwin",
        other => other,
    };
    format!("{}-{}", std::env::consts::ARCH, os)
}
